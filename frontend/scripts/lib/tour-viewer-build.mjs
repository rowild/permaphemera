// The fingerprint in the tour viewer's URLs (2026-10-22).
//
// tour-viewer.js and tour-viewer.css keep their names on every update, so
// browsers and Cloudflare served an old copy for up to 4 hours after one.
// `pnpm viewer:update` therefore records a fingerprint of the two files in
// app/utils/tourViewerBuild.ts, and useTourViewer puts it into both URLs
// (`tour-viewer.js?v=<fingerprint>`): a changed viewer is a new address no
// cache has seen, an unchanged one keeps its cache.
import { createHash } from 'node:crypto'

/** Ten hex characters of a SHA-256 over both files. */
export function viewerBuildId(jsBytes, cssBytes) {
  return createHash('sha256').update(jsBytes).update('\0').update(cssBytes).digest('hex').slice(0, 10)
}

/** The source of app/utils/tourViewerBuild.ts for one fingerprint. */
export function buildModuleSource(id) {
  return `// Generated by \`pnpm viewer:update\` (scripts/update-tour-viewer.mjs) — do not edit.
// A fingerprint of public/media/tour-viewer/tour-viewer.js + .css. It goes into
// their URLs, so every viewer update gets a new address that no browser or
// Cloudflare cache has seen. test/unit/tour-viewer-build.spec.ts checks that it
// matches the files.
export const TOUR_VIEWER_BUILD = '${id}'
`
}
